def _infer_resource_type(resource_id: str, metadata: Optional[Dict[str, Any]] = None) -> str:
    """Infers or retrieves the canonical asset type for actuation routing."""
    if metadata and "type" in metadata:
        return metadata["type"]
    rid_lower = resource_id.lower()
    if "plc" in rid_lower:
        return "plc_controller"
    if "med" in rid_lower or "medical" in rid_lower:
        return "medical_device"
    if "camera" in rid_lower or "sensor" in rid_lower:
        return "camera_sensor"
    if "router" in rid_lower or "gateway" in rid_lower or "switch" in rid_lower or "gw" in rid_lower:
        return "network_gateway"
    if "db" in rid_lower or "rds" in rid_lower or "sql" in rid_lower:
        return "rds_database"
    if "iam" in rid_lower or "role" in rid_lower or "user" in rid_lower:
        return "iam_role"
    return "ec2_instance"


def _execute_action(
    resource_id: str,
    action: str,
    step: Optional[int] = None,
    resource_meta: Optional[Dict[str, Any]] = None,
) -> dict:
    """
    Executes an action by dispatching machine-level control commands to the
    appropriate physical or cloud interface.
    """
    timestamp = datetime.datetime.now().isoformat(timespec="seconds")
    step_str = f" (Step {step})" if step is not None else ""
    description = ACTION_DESCRIPTIONS.get(action, f"Executing {action}")

    rtype = _infer_resource_type(resource_id, resource_meta)

    # Route to appropriate actuation driver based on cyber-physical taxonomy
    if rtype == "plc_controller":
        actuator_record = ModbusActuator.dispatch(resource_id, action)
    elif rtype in ("medical_device", "camera_sensor"):
        actuator_record = OpcUaActuator.dispatch(resource_id, action)
    elif rtype in ("network_gateway", "vpc_router", "load_balancer"):
        actuator_record = NetworkSwitchActuator.dispatch(resource_id, action)
    else:
        actuator_record = CloudHypervisorActuator.dispatch(resource_id, action)

    log_line = (
        f"[{timestamp}] {resource_id}{step_str}: {description} "
        f"[Interface: {actuator_record['interface']} | Protocol: {actuator_record['protocol']}]"
    )
    print(log_line)

    return {
        "resource_id": resource_id,
        "action": action,
        "step": step,
        "timestamp": timestamp,
        "status": "simulated_success",  # Preserves exact backward-compatible verification assertion
        "protocol": actuator_record["protocol"],
        "interface_type": actuator_record["interface"],
        "actuation_command": actuator_record,
        "resource_type": rtype,
    }


def execute_plan(
    plan: dict,
    resource_metadata: Optional[Dict[str, Dict[str, Any]]] = None,
) -> list:
    """
    plan: {resource_id: action}
    resource_metadata: optional {resource_id: {type: ...}}
    Returns list of execution log records with protocol-level actuation commands.
    """
    meta_map = resource_metadata or {}
    return [_execute_action(rid, action, resource_meta=meta_map.get(rid)) for rid, action in plan.items()]


def execute_strategy(
    strategy_name: str,
    plan: dict,
    step_delay: float = 0.5,
    resource_metadata: Optional[Dict[str, Dict[str, Any]]] = None,
) -> list:
    """
    Executes a multi-step response strategy across physical and cloud actuation interfaces.
    Returns a list of all log records from all steps.
    """
    all_logs = []
    strategy = RESPONSE_STRATEGIES.get(strategy_name, [])
    meta_map = resource_metadata or {}
    step_num = 1

    for action in strategy:
        for resource_id in plan:
            log = _execute_action(resource_id, action, step_num, resource_meta=meta_map.get(resource_id))
            all_logs.append(log)
        step_num += 1
        time.sleep(step_delay)

    return all_logs


