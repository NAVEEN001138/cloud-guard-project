    demo_plan = {"vm-1": "isolate", "iam-role-2": "rotate_credentials"}
    logs1 = execute_plan(demo_plan)

    print("\n=== Layer 8: Testing multi-step strategy (Strategy A) ===")
    logs2 = execute_strategy("Strategy A", demo_plan)
